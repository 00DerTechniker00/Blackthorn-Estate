import fs from 'node:fs';
import assert from 'node:assert/strict';
import {validateBlueprint} from '../js/data.js';
const d=JSON.parse(fs.readFileSync(new URL('../blueprint.json',import.meta.url)));
const r=validateBlueprint(d);
assert.deepEqual(r.errors,[],r.errors.join(' | '));
assert.equal(d.blocks.length,50630);
assert.equal(d.version,'6.0');
assert.deepEqual(r.warnings,[],r.warnings.join(' | '));
const modified={...d,blocks:[...d.blocks,d.blocks[0]]};
assert.ok(validateBlueprint(modified).errors.some(e=>e.includes('Doppelte')));
const broken={...d,palette:{}};
assert.ok(validateBlueprint(broken).errors.length>0);
console.log('Blueprint V6 geprüft:',d.blocks.length,'eindeutige Positionen,',Object.keys(r.actual).length,'Materialien,',Object.keys(r.actualGroups).length,'Baugruppen.');
